"""Scope-to-scenario coverage for the E2E suite (issue #140).

``tests/config/scope.yaml`` lists the regression scope; every scenario may
declare the scope entries it covers with a ``covers`` list. This module joins
the two, reports gaps, and renders ``tests/docs/coverage.md``.

The check is deliberately host-free: it reads YAML, the scenario schema and the
device matrix, so the ``harness`` CI job can run it without Docker or the
Connect IQ SDK. It does not claim a scenario passed; it proves that every scope
entry has a scenario or an explicit waiver, and that no scenario references an
unknown entry.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Mapping, Optional, Sequence, Tuple

from .config import (
    DOCS_DIR,
    SCOPE_FILE,
    ConfigError,
    Device,
    default_device_id,
    load_devices,
)
from .scenarios import Scenario, discover_scenarios
from .scope import Scope, ScopeBlocked, ScopeEntry, ScopeWaiver, load_scope
from .languages import provisionable_languages
from .variants import matrix_problems

COVERAGE_DOC = DOCS_DIR / "coverage.md"

GENERATED_NOTICE = (
    "<!-- Generated by `python -m e2e coverage --write` from "
    "tests/config/scope.yaml and the scenario `covers` keys. Do not edit by hand. -->"
)


class CoverageError(ConfigError):
    """Raised when the coverage inputs cannot be loaded."""


@dataclass(frozen=True)
class CoverageProblem:
    """One reason the scope is not fully accounted for."""

    kind: str
    detail: str

    def __str__(self) -> str:
        return f"{self.kind}: {self.detail}"


#: The provisionable language set comes from the measured ``Language`` index map
#: (``e2e.languages``), the same source the engine and the Wine driver use. A
#: code without a measured index is labelled blocked for the reviewed document;
#: `python -m e2e language-scan --write` is what unblocks it.
def blocked_languages(languages: Sequence[str]) -> Tuple[str, ...]:
    """Languages in a matrix the environment cannot provision."""
    runnable = set(provisionable_languages())
    return tuple(language for language in languages if language not in runnable)


@dataclass(frozen=True)
class ScenarioGroup:
    """Expanded language runs of one scenario file, for display."""

    suite: str
    base_name: str
    tier: str
    device: str
    languages: Tuple[str, ...]
    manual_checks: Tuple[str, ...]

    @property
    def label(self) -> str:
        return self.describe()

    @property
    def blocked(self) -> Tuple[str, ...]:
        return blocked_languages(self.languages)

    def describe(self, default_device: str = "") -> str:
        device = self.device
        if device == "any":
            device = f"any -> {default_device}" if default_device else "any"
        suffix = ""
        if len(self.languages) > 1:
            runnable = [lang for lang in self.languages if lang not in self.blocked]
            suffix = (
                f", {len(self.languages)} languages "
                f"({', '.join(runnable)} runnable"
            )
            if self.blocked:
                suffix += f"; {', '.join(self.blocked)} blocked"
            suffix += ")"
        return f"`{self.suite}/{self.base_name}` ({self.tier}, {device}{suffix})"


@dataclass(frozen=True)
class EntryCoverage:
    """One scope entry and the scenarios and/or waiver that account for it."""

    entry: ScopeEntry
    scenarios: Tuple[Scenario, ...]
    groups: Tuple[ScenarioGroup, ...]
    waiver: Optional[ScopeWaiver]
    blocked: Optional[ScopeBlocked] = None

    @property
    def status(self) -> str:
        if self.scenarios:
            return "covered"
        if self.blocked is not None:
            return "blocked"
        if self.waiver is not None:
            return "waived"
        return "empty"


@dataclass(frozen=True)
class CoverageReport:
    """The complete mapping, plus every gap."""

    scope: Scope
    entries: Tuple[EntryCoverage, ...]
    problems: Tuple[CoverageProblem, ...]
    scenarios: Tuple[Scenario, ...]

    @property
    def covered(self) -> Tuple[EntryCoverage, ...]:
        return tuple(entry for entry in self.entries if entry.status == "covered")

    @property
    def waived(self) -> Tuple[EntryCoverage, ...]:
        return tuple(entry for entry in self.entries if entry.status == "waived")

    @property
    def blocked(self) -> Tuple[EntryCoverage, ...]:
        return tuple(entry for entry in self.entries if entry.status == "blocked")

    @property
    def empty(self) -> Tuple[EntryCoverage, ...]:
        return tuple(entry for entry in self.entries if entry.status == "empty")

    @property
    def scenario_files(self) -> int:
        return len({scenario.source for scenario in self.scenarios})

    @property
    def blocked_language_runs(self) -> int:
        """Expanded runs whose language the environment cannot provision."""
        return sum(
            1
            for scenario in self.scenarios
            if scenario.language not in set(provisionable_languages())
        )

    @property
    def uncovered_scenarios(self) -> Tuple[Scenario, ...]:
        """Scenarios that do not declare a scope entry."""
        return tuple(scenario for scenario in self.scenarios if not scenario.covers)


