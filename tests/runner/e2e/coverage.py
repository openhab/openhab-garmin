def _cell(text: str) -> str:
    """Make text safe inside a Markdown table cell."""
    return " ".join(text.replace("|", "\\|").splitlines())


def _waiver_cell(waiver: ScopeWaiver) -> str:
    cell = f"Waived: {_cell(waiver.reason)}"
    if waiver.verified_by:
        cell += f" (verified by `{_cell(waiver.verified_by)}`)"
    return cell


def _blocked_cell(blocked: ScopeBlocked, scope: Scope) -> str:
    """A blocked entry names the limitation and links to its tracked issue."""
    return (
        f"**Blocked:** {_cell(blocked.reason)} "
        f"([#{blocked.issue}]({scope.issue_url(blocked.issue)}))"
    )


def _manual_cell(groups: Sequence[ScenarioGroup]) -> str:
    parts: List[str] = []
    for group in groups:
        for check in group.manual_checks:
            parts.append(f"`{group.suite}/{group.base_name}`: {_cell(check)}")
    return "<br>".join(parts) if parts else "—"


def render_markdown(
    report: CoverageReport,
    devices: Optional[Sequence[Device]] = None,
) -> str:
    """Render the reviewed, checked-in coverage document."""
    devices = tuple(devices) if devices is not None else tuple(load_devices())
    default_id = ""
    if any(scenario.device == "any" for scenario in report.scenarios):
        try:
            default_id = default_device_id()
        except ConfigError:
            default_id = devices[0].id if devices else ""

    total = len(report.entries)
    covered = len(report.covered)
    waived = len(report.waived)
    blocked = len(report.blocked)
    empty = len(report.empty)

    lines: List[str] = [
        "# Regression coverage matrix",
        "",
        GENERATED_NOTICE,
        "",
        f"Source: [#{report.scope.issue}]({report.scope.source}).",
        "",
        "## Summary",
        "",
        "| Measure | Count |",
        "| --- | --- |",
        f"| Scope entries | {total} |",
        f"| Covered by at least one scenario | {covered} |",
        f"| Waived with a reason | {waived} |",
        f"| Blocked by a tracked issue | {blocked} |",
        f"| Empty (must be 0) | {empty} |",
        f"| Scenario files | {report.scenario_files} |",
        f"| Expanded scenario runs | {len(report.scenarios)} |",
        f"| Language variants blocked (no measured index) | {report.blocked_language_runs} |",
        "",
        "> **Host-only execution.** Every scenario listed below needs a Linux host",
        "> with Docker, the Connect IQ SDK and the simulator. The `harness` CI job",
        "> validates the scenario schema, the dry run, the golden policy and this",
        "> mapping; it never launches the simulator and **does not claim pixel",
        "> parity**. A waiver is a deliberate gap rather than a passing test. A",
        "> scenario is evidence only after it has run on the guest; the last",
        "> recorded guest contract run is 12 pass / 0 fail / 6 skipped, and this",
        "> document itself never executes anything.",
        ">",
        "> **Verified automatically on the Linux host:** build, launch, navigation,",
        "> openHAB requests, response parsing, view identity, error classes,",
        "> payload limits, languages, and the Connect IQ unit tests. These are",
        "> structure and protocol facts: what a green run on the guest means.",
        ">",
        "> **Verified only on Windows:** rendering — text, layout, truncation and",
        "> translations. The guest's Wine execution path raises",
        "> `Invalid Font Specified` while drawing the glance, the homepage and the",
        "> error view, while the same PRG renders with text in the Windows",
        "> simulator. A screenshot from the guest is therefore a crashed render,",
        "> so **a golden must come from a Windows run** and `--update-goldens` is",
        "> refused for the Wine driver. See [visual-truth.md](visual-truth.md).",
        ">",
        "> **The glance is excluded from E2E builds.** On the Wine guest the app",
        "> raises `Invalid Font Specified` on its first glance draw, so every",
        "> scenario builds with the `watch-app` profile, whose glance view is",
        "> replaced by an empty stub and draws nothing. Glance-related entries are",
        "> **blocked**, not waived, and no green run is glance coverage. Re-enable",
        "> it with `python -m e2e run --with-glance` (or `e2e build --with-glance`)",
        "> on a host that paints text, or once",
        "> [#396](https://github.com/openhab/openhab-garmin/issues/396) is resolved;",
        "> see [simulator-driver.md](simulator-driver.md#glance-the-profile-that-keeps-runs-alive).",
        ">",
        "> **Every language in the matrix is provisioned.** The simulator stores",
        "> the language as a numeric index; every language in the matrix is",
        "> provisioned through it (`deu` is 7) and verified from the trace, so no",
        "> language variant is blocked. See",
        "> [simulator-driver.md](simulator-driver.md#language-is-a-numeric-index).",
        "",
        "A scenario may exercise part of an entry and mark the rest in",
        "`manual_checks`; those checks are listed in the last column and are not",
        "machine-asserted.",
        "",
    ]

    for section in report.scope.sections:
        entries = [entry for entry in report.entries if entry.entry.section == section.id]
        if not entries:
            continue
        lines.extend(
            [
                f"## {section.label}",
                "",
                "| Scope id | Title | Status | Scenarios or waiver | Manual checks |",
                "| --- | --- | --- | --- | --- |",
            ]
        )
        for entry in entries:
            if entry.scenarios:
                scenarios = "<br>".join(
                    group.describe(default_id) for group in entry.groups
                )
            elif entry.blocked is not None:
                scenarios = _blocked_cell(entry.blocked, report.scope)
            else:
                scenarios = _waiver_cell(entry.waiver) if entry.waiver else ""
            lines.append(
                "| "
                + " | ".join(
                    [
                        f"`{entry.entry.id}`",
                        _cell(entry.entry.title),
                        entry.status.capitalize(),
                        scenarios or "—",
                        _manual_cell(entry.groups),
                    ]
                )
                + " |"
            )
        lines.append("")

    if report.uncovered_scenarios:
        lines.extend(
            [
                "## Scenarios without a scope entry",
                "",
                "These scenarios are not evidence for a #140 bullet. Add a `covers`",
                "key if that is wrong.",
                "",
            ]
        )
        for scenario in report.uncovered_scenarios:
            lines.append(f"- `{scenario.scenario_id}`")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def write_markdown(
    report: CoverageReport,
    path: Path = COVERAGE_DOC,
    devices: Optional[Sequence[Device]] = None,
) -> Path:
    """Write the generated document and return its path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown(report, devices=devices), encoding="utf-8")
    return path


def document_is_current(
    report: CoverageReport,
    path: Path = COVERAGE_DOC,
    devices: Optional[Sequence[Device]] = None,
) -> bool:
    """True when the checked-in document matches the current inputs."""
    if not path.is_file():
        return False
    return path.read_text(encoding="utf-8") == render_markdown(report, devices=devices)


