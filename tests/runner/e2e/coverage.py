def report_document(report: CoverageReport) -> Mapping[str, object]:
    """Return a JSON-serialisable view used by ``e2e coverage --json``."""
    return {
        "issue": report.scope.issue,
        "source": report.scope.source,
        "counts": {
            "entries": len(report.entries),
            "covered": len(report.covered),
            "waived": len(report.waived),
            "empty": len(report.empty),
            "scenario_files": report.scenario_files,
            "scenario_runs": len(report.scenarios),
        },
        "entries": [
            {
                "id": entry.entry.id,
                "section": entry.entry.section,
                "title": entry.entry.title,
                "status": entry.status,
                "scenarios": [
                    {
                        "scenario": scenario.scenario_id,
                        "tier": scenario.tier,
                        "device": scenario.device,
                        "language": scenario.language,
                    }
                    for scenario in entry.scenarios
                ],
                "manual_checks": [
                    check for group in entry.groups for check in group.manual_checks
                ],
                "waiver": (
                    None
                    if entry.waiver is None
                    else {
                        "reason": entry.waiver.reason,
                        "verified_by": entry.waiver.verified_by,
                    }
                ),
            }
            for entry in report.entries
        ],
        "problems": [str(problem) for problem in report.problems],
        "ok": not report.problems,
    }
