def _group_scenarios(scenarios: Sequence[Scenario]) -> Tuple[ScenarioGroup, ...]:
    grouped: Dict[Tuple[str, str], List[Scenario]] = {}
    for scenario in scenarios:
        grouped.setdefault((scenario.suite, scenario.base_name), []).append(scenario)

    groups: List[ScenarioGroup] = []
    for (suite, base_name), runs in sorted(grouped.items()):
        first = runs[0]
        manual: List[str] = []
        for run in runs:
            for check in run.manual_checks:
                if check not in manual:
                    manual.append(check)
        groups.append(
            ScenarioGroup(
                suite=suite,
                base_name=base_name,
                tier=first.tier,
                device=first.device,
                languages=tuple(run.language for run in runs),
                manual_checks=tuple(manual),
            )
        )
    return tuple(groups)


def build_report(
    scenarios: Optional[Sequence[Scenario]] = None,
    scope: Optional[Scope] = None,
    devices: Optional[Sequence[Device]] = None,
    *,
    check_device_matrix: bool = True,
) -> CoverageReport:
    """Join the scope and the scenarios, and list every gap."""
    scope = scope or load_scope()
    scenarios = tuple(scenarios) if scenarios is not None else tuple(discover_scenarios())
    devices = tuple(devices) if devices is not None else tuple(load_devices())

    problems: List[CoverageProblem] = []
    known = set(scope.entry_ids)

    by_entry: Dict[str, List[Scenario]] = {entry.id: [] for entry in scope.entries}
    for scenario in scenarios:
        if not scenario.covers:
            continue
        for entry_id in scenario.covers:
            if entry_id not in known:
                problems.append(
                    CoverageProblem(
                        "unknown-scope",
                        f"{scenario.scenario_id} covers unknown scope id {entry_id!r}",
                    )
                )
                continue
            by_entry[entry_id].append(scenario)

    waiver_by_id = {waiver.id: waiver for waiver in scope.waivers}
    entries: List[EntryCoverage] = []
    for entry in scope.entries:
        covering = tuple(by_entry[entry.id])
        waiver = waiver_by_id.get(entry.id)
        if covering and waiver is not None:
            problems.append(
                CoverageProblem(
                    "redundant-waiver",
                    f"{entry.id} is covered by "
                    f"{', '.join(scenario.scenario_id for scenario in covering)} "
                    "and also has a waiver",
                )
            )
        if not covering and waiver is None:
            problems.append(
                CoverageProblem(
                    "uncovered",
                    f"{entry.id} has no scenario and no waiver ({entry.title})",
                )
            )
        entries.append(
            EntryCoverage(
                entry=entry,
                scenarios=covering,
                groups=_group_scenarios(covering),
                waiver=waiver,
            )
        )

    if check_device_matrix and any(waiver.verified_by for waiver in scope.waivers):
        for problem in matrix_problems():
            problems.append(
                CoverageProblem("device-matrix", str(problem))
            )

    return CoverageReport(
        scope=scope,
        entries=tuple(entries),
        problems=tuple(problems),
        scenarios=scenarios,
    )


