def _cell(text: str) -> str:
    """Make text safe inside a Markdown table cell."""
    return " ".join(text.replace("|", "\\|").splitlines())


def _waiver_cell(waiver: ScopeWaiver) -> str:
    cell = f"Waived: {_cell(waiver.reason)}"
    if waiver.verified_by:
        cell += f" (verified by `{_cell(waiver.verified_by)}`)"
    return cell


def _manual_cell(groups: Sequence[ScenarioGroup]) -> str:
    parts: List[str] = []
    for group in groups:
        for check in group.manual_checks:
            parts.append(f"`{group.suite}/{group.base_name}`: {_cell(check)}")
    return "<br>".join(parts) if parts else "—"


def render_markdown(
    report: CoverageReport,
    devices: Optional[Sequence[Device]] = None,
) -> str:
    """Render the reviewed, checked-in coverage document."""
    devices = tuple(devices) if devices is not None else tuple(load_devices())
    default_id = ""
    if any(scenario.device == "any" for scenario in report.scenarios):
        try:
            default_id = default_device_id()
        except ConfigError:
            default_id = devices[0].id if devices else ""

    total = len(report.entries)
    covered = len(report.covered)
    waived = len(report.waived)
    empty = len(report.empty)

    lines: List[str] = [
        "# Regression coverage matrix",
        "",
        GENERATED_NOTICE,
        "",
        f"Source: [#{report.scope.issue}]({report.scope.source}).",
        "",
        "## Summary",
        "",
        "| Measure | Count |",
        "| --- | --- |",
        f"| Scope entries | {total} |",
        f"| Covered by at least one scenario | {covered} |",
        f"| Waived with a reason | {waived} |",
        f"| Empty (must be 0) | {empty} |",
        f"| Scenario files | {report.scenario_files} |",
        f"| Expanded scenario runs | {len(report.scenarios)} |",
        "",
        "> **Host-only execution.** Every scenario listed below needs a Linux host",
        "> with Docker, the Connect IQ SDK and the simulator. The `harness` CI job",
        "> validates the scenario schema, the dry run and this mapping; it never",
        "> executes a scenario. Nothing in this table has been run against the stack",
        "> yet, and a waiver is a deliberate gap rather than a passing test.",
        "",
        "A scenario may exercise part of an entry and mark the rest in",
        "`manual_checks`; those checks are listed in the last column and are not",
        "machine-asserted.",
        "",
    ]

    for section in report.scope.sections:
        entries = [entry for entry in report.entries if entry.entry.section == section.id]
        if not entries:
            continue
        lines.extend(
            [
                f"## {section.label}",
                "",
                "| Scope id | Title | Status | Scenarios or waiver | Manual checks |",
                "| --- | --- | --- | --- | --- |",
            ]
        )
        for entry in entries:
            if entry.scenarios:
                scenarios = "<br>".join(
                    group.describe(default_id) for group in entry.groups
                )
            else:
                scenarios = _waiver_cell(entry.waiver) if entry.waiver else ""
            lines.append(
                "| "
                + " | ".join(
                    [
                        f"`{entry.entry.id}`",
                        _cell(entry.entry.title),
                        entry.status.capitalize(),
                        scenarios or "—",
                        _manual_cell(entry.groups),
                    ]
                )
                + " |"
            )
        lines.append("")

    if report.uncovered_scenarios:
        lines.extend(
            [
                "## Scenarios without a scope entry",
                "",
                "These scenarios are not evidence for a #140 bullet. Add a `covers`",
                "key if that is wrong.",
                "",
            ]
        )
        for scenario in report.uncovered_scenarios:
            lines.append(f"- `{scenario.scenario_id}`")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def write_markdown(
    report: CoverageReport,
    path: Path = COVERAGE_DOC,
    devices: Optional[Sequence[Device]] = None,
) -> Path:
    """Write the generated document and return its path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown(report, devices=devices), encoding="utf-8")
    return path


def document_is_current(
    report: CoverageReport,
    path: Path = COVERAGE_DOC,
    devices: Optional[Sequence[Device]] = None,
) -> bool:
    """True when the checked-in document matches the current inputs."""
    if not path.is_file():
        return False
    return path.read_text(encoding="utf-8") == render_markdown(report, devices=devices)


