class BuildError(RuntimeError):
    """Raised when ``monkeyc`` fails or is not usable."""


#: Build profile names, printed by ``e2e build`` and at the top of a run.
#:
#: A widget shown on the glance page is started in **glance mode** (32 KB
#: budget) and enters ``getInitialView()`` when it is selected; the driver
#: selects it with DOWN then SELECT. ``watch-app`` still declares the app as a
#: plain watch app in a harness-owned copy of ``manifest.xml`` (the only valid
#: plain-app type in ``monkeybrains.jar``'s ``AppTypeManager`` is ``watch-app``),
#: so a run launches the initial view directly and does not depend on the glance
#: page. The widget and glance modes stay explicitly unverified: no scenario
#: visits them.
PROFILE_WATCH_APP = "watch-app"
PROFILE_WITH_GLANCE = "with-glance"
PROFILE_WITHOUT_GLANCE = "without-glance"
PROFILES: Tuple[str, ...] = (
    PROFILE_WATCH_APP,
    PROFILE_WITHOUT_GLANCE,
    PROFILE_WITH_GLANCE,
)

#: The manifest's application type the profiles switch between.
_MANIFEST_TYPE = re.compile(r'(<iq:application\b[^>]*\btype=")widget(")')

#: The app's glance view, relative to the checkout. This is the file the
#: ``without-glance`` profile stubs out; a guard test compares it with the
#: annotation in the app source so moving the real file fails loudly.
GLANCE_VIEW = Path("source/main/user-interface/features/glance/GlanceSitemapView.mc")

#: Directory (below the build output) holding the stubbed source copy.
GLANCE_STUB_SOURCE = "source-no-glance"

#: The stub that replaces :data:`GLANCE_VIEW`. It deliberately draws nothing:
#: the crash is in the glance's text rendering, and leaving the registration in
#: place is the smallest change that keeps the app's initial view intact.
GLANCE_STUB = '''import Toybox.Graphics;
import Toybox.Lang;
import Toybox.WatchUi;

/*
 * E2E build stub, generated by the harness; the checkout is not modified.
 *
 * The harness stubs the real glance view so scenarios launch the app's normal
 * initial view instead of depending on the glance page; the glance itself is
 * not verified by the suite. The historical "Invalid Font Specified" draw crash
 * was the missing device font pack, which the runner stages.
 * This stub keeps getGlanceView() valid and draws nothing, so scenarios
 * exercise the app's normal initial view.
 *
 * It keeps the (:glance) scope annotation: OHApp's getGlanceView() is a
 * glance-scope function and may only reference glance-scope values.
 */
(:glance)
class GlanceSitemapView extends WatchUi.GlanceView {

    public function initialize() {
        GlanceView.initialize();
    }

    public function onLayout( dc as Graphics.Dc ) as Void {
    }

    public function onUpdate( dc as Graphics.Dc ) as Void {
    }
}
'''


def describe_profile(profile: str) -> str:
    """One line naming the profile and what it means for coverage."""
    if profile not in PROFILES:
        raise BuildError(f"unknown build profile {profile!r}; expected {', '.join(PROFILES)}")
    if profile == PROFILE_WITH_GLANCE:
        return (
            f"{PROFILE_WITH_GLANCE}: the app's own glance view is compiled; the "
            "glance is not yet verified on this host, so review what it draws"
        )
    if profile == PROFILE_WITHOUT_GLANCE:
        return (
            f"{PROFILE_WITHOUT_GLANCE}: the glance view is replaced by an empty "
            "stub and draws nothing; the app is still a widget, so the simulator "
            "may start it in glance mode; the glance is NOT covered (not yet "
            "verified)"
        )
    return (
        f"{PROFILE_WATCH_APP}: the app is declared as a plain watch app in a "
        "generated manifest and its glance view is stubbed, so the simulator "
        "launches getInitialView() directly; widget and glance modes are NOT "
        "covered (not yet verified)"
    )


def write_watch_app_manifest(source_root: Path, output_dir: Path) -> Path:
    """Write a manifest declaring the app as a plain watch app.

    The checkout's ``manifest.xml`` stays untouched: the copy lives in the build
    output and the generated jungle's ``project.manifest`` points at it. That is
    what stops the simulator from starting the app in glance mode.
    """
    source = Path(source_root) / "manifest.xml"
    try:
        text = source.read_text(encoding="utf-8")
    except OSError as error:
        raise BuildError(f"cannot read {source}: {error}") from None
    replaced, count = _MANIFEST_TYPE.subn(r"\g<1>watch-app\g<2>", text)
    if count == 0:
        raise BuildError(
            f"{source} has no <iq:application ... type=\"widget\"> entry to "
            "switch to the watch-app profile"
        )
    target = Path(output_dir) / "manifest-watch-app.xml"
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(replaced, encoding="utf-8")
    except OSError as error:
        raise BuildError(f"cannot write {target}: {error}") from None
    return target


@dataclass(frozen=True)
class BuildResult:
    """A compiled PRG plus the exact invocation used."""

    prg: Path
    command: Tuple[str, ...]
    output: str
    duration_ms: float
    jungle: Path
    jungle_generated: bool
    jungle_note: str
    settings_json: Optional[Path] = None
    settings_values: Mapping[str, Any] = field(default_factory=dict)
    profile: str = PROFILE_WITH_GLANCE
    profile_note: str = ""


def prg_name(device: str) -> str:
    return f"openhab-garmin-{device}.prg"


#: Properties whose compiled defaults are asserted after every build. If the
#: resource override stops applying, the app would run without a server URL and
#: every scenario would pass vacuously, so this is checked before the guest ever
#: sees the PRG.
ASSERTED_PROPERTIES: Tuple[str, ...] = ("url_0", "sitemap_0")

#: Property ids as ``settings.xml`` spells them: a name and an index.
_PROPERTY_ID = re.compile(r"^[A-Za-z][A-Za-z0-9]*_\d+$")


def settings_json_candidates(prg: Path) -> Tuple[Path, ...]:
    """Where ``monkeyc`` writes the compiled property defaults.

    ``monkeyc -o app.prg`` emits the values it compiled next to the PRG. The
    name has been seen both as ``app-settings.json`` and ``app.prg-settings.json``
    across SDK builds, so both are accepted.
    """
    return (
        Path(prg).with_name(f"{Path(prg).stem}-settings.json"),
        Path(f"{prg}-settings.json"),
    )


def read_compiled_settings(path: Path) -> Dict[str, Any]:
    """Extract ``property id -> default value`` from ``monkeyc``'s JSON.

    The exact document shape is SDK-specific; ids are found wherever they carry
    a ``defaultValue``, and a flat ``id -> value`` mapping is accepted too.
    """
    try:
        document = json.loads(Path(path).read_text(encoding="utf-8"))
    except OSError as error:
        raise BuildError(f"cannot read {path}: {error}") from None
    except ValueError as error:
        raise BuildError(f"{path} is not valid JSON: {error}") from None

    values: Dict[str, Any] = {}

    def collect(node: Any) -> None:
        if isinstance(node, Mapping):
            name = node.get("id") or node.get("name") or node.get("key")
            if isinstance(name, str) and "defaultValue" in node:
                values[name] = node["defaultValue"]
                return
            for key, value in node.items():
                if isinstance(value, Mapping) and "defaultValue" in value:
                    values[str(key)] = value["defaultValue"]
                elif isinstance(value, (Mapping, list)):
                    collect(value)
                elif isinstance(key, str) and _PROPERTY_ID.match(key):
                    values[key] = value
        elif isinstance(node, list):
            for item in node:
                collect(item)

    collect(document)
    return values


def verify_compiled_settings(
    prg: Path, settings: AppSettings
) -> Tuple[Path, Dict[str, Any]]:
    """Assert the PRG really contains the configured property defaults.

    Runs with no simulator and no display, so a silent resource-override
    regression fails the build instead of reaching the guest.
    """
    path = next((candidate for candidate in settings_json_candidates(prg) if candidate.is_file()), None)
    if path is None:
        expected = " or ".join(str(candidate) for candidate in settings_json_candidates(prg))
        raise BuildError(
            f"monkeyc did not write the compiled settings JSON (looked for "
            f"{expected}).\n"
            "The settings resource override is the only way the harness sets the "
            "app's property defaults, so a run without it would show the "
            "configuration error view. Check that the generated jungle lists "
            "the resource override after `$(resBase)`."
        )
    values = read_compiled_settings(path)
    problems = []
    for name in ASSERTED_PROPERTIES:
        requested = settings.properties.get(name)
        if name not in values:
            problems.append(f"{name}: missing from {path.name}")
        elif str(values[name]) != str(requested):
            problems.append(
                f"{name}: compiled {values[name]!r} but the build requested {requested!r}"
            )
    if problems:
        raise BuildError(
            "the compiled app properties do not match the build settings:\n  "
            + "\n  ".join(problems)
            + f"\nsettings source: {path}\n"
            "The resource override did not win over resources/base. Check the "
            "generated jungle's <device>.resourcePath order."
        )
    return path, values


def _run_openssl(openssl: str, arguments: Sequence[str]) -> None:
    try:
        completed = subprocess.run(  # noqa: S603 - fixed argument list
            [openssl, *arguments],
            capture_output=True,
            text=True,
            timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise BuildError(f"cannot run openssl: {error}") from None
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout or "").strip()
        raise BuildError(
            f"openssl {arguments[0]} failed (exit {completed.returncode}): {detail}"
        )


@contextmanager
def ephemeral_developer_key(
    directory: Path,
    *,
    openssl: Optional[str] = None,
) -> Iterator[Path]:
    """Yield a throwaway RSA developer key for ``monkeyc -y``.

    ``monkeyc`` refuses to compile without a private key, which made an
    unattended ``e2e build`` impossible. The key only signs a build for the
    simulator; it is not the Connect IQ store key and it proves nothing about
    ownership, but it must not be reused or committed all the same.

    The key is generated with ``openssl`` (RSA 4096, PKCS#8 DER, the format
    monkeyc wants), stored under the caller's artifacts directory — never in the
    checkout — with mode ``0600``, and removed when the context exits. Every
    invocation therefore gets a fresh key. ``--developer-key`` remains the
    override for callers that have a stable key.
    """
    binary = openssl or shutil.which("openssl")
    if binary is None:
        raise BuildError(
            "openssl is required to generate the ephemeral developer key; install "
            "openssl or pass an explicit --developer-key"
        )

    keys_dir = Path(directory) / "keys"
    keys_dir.mkdir(parents=True, exist_ok=True)
    token = f"{os.getpid()}-{time.time_ns()}"
    pem = keys_dir / f"developer-key-{token}.pem"
    der = keys_dir / f"developer-key-{token}.der"
    try:
        _run_openssl(binary, ["genrsa", "-out", str(pem), "4096"])
        _run_openssl(
            binary,
            [
                "pkcs8",
                "-topk8",
                "-inform",
                "PEM",
                "-outform",
                "DER",
                "-in",
                str(pem),
                "-out",
                str(der),
                "-nocrypt",
            ],
        )
        os.chmod(der, 0o600)
        yield der
    finally:
        for path in (pem, der):
            try:
                path.unlink()
            except FileNotFoundError:
                pass


def write_glance_excluded_source(source_root: Path, output_dir: Path) -> Path:
    """Copy ``source/`` below ``output_dir`` with the glance view stubbed.

    The checkout is treated as read-only (and must stay unmodified), so the
    profile works on a generated mirror. Only ``source/`` is copied;
    ``manifest.xml`` and ``resources/`` keep coming from the checkout, and the
    generated jungle's ``sourcePath`` entries are rebased onto the mirror.

    The stub sits at the same relative path as the real file, so the class name
    that ``OHApp.getGlanceView()`` references still resolves.
    """
    source_root = Path(source_root)
    overlay = Path(output_dir) / GLANCE_STUB_SOURCE
    target = overlay / "source"
    if not (source_root / "source").is_dir():
        raise BuildError(
            f"cannot build the {PROFILE_WITHOUT_GLANCE} profile: "
            f"{source_root / 'source'} is not a directory"
        )
    try:
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(source_root / "source", target)
        stub = overlay / GLANCE_VIEW
        stub.parent.mkdir(parents=True, exist_ok=True)
        stub.write_text(GLANCE_STUB, encoding="utf-8")
    except OSError as error:
        raise BuildError(
            f"cannot write the {PROFILE_WITHOUT_GLANCE} source overlay in "
            f"{overlay}: {error}"
        ) from None
    return overlay


def build_prg(
    layout: SdkLayout,
    device: str,
    output_dir: Path,
    *,
    jungle: Optional[Path] = None,
    release: bool = False,
    developer_key: Optional[Path] = None,
    settings: Optional[AppSettings] = None,
    settings_source: Optional[Path] = None,
    extra_args: Sequence[str] = (),
    env: Optional[dict] = None,
    profile: str = PROFILE_WITH_GLANCE,
) -> BuildResult:
    """Compile the app for one device.

    ``release`` defaults to False on purpose: the E2E trace events are debug
    annotations, and a release build silently removes the harness's event
    assertions.

    By default the jungle is generated for ``device`` from the checkout's
    ``monkey.jungle`` and written to ``output_dir``. That is what lets a reduced
    SDK compile at all: the full jungle names every supported device, and
    ``monkeyc`` rejects qualifiers the SDK does not define. ``jungle`` is the
    ``--jungle`` escape hatch for a complete SDK.

    ``profile`` selects the build profile:

    - ``watch-app`` (the CLI default for scenarios) copies ``source/`` with the
      glance view stubbed and writes a manifest declaring ``type="watch-app"``,
      so a run launches ``getInitialView()`` directly instead of depending on
      the glance page (the widget and glance modes are not yet verified);
    - ``without-glance`` only stubs the glance view;
    - ``with-glance`` compiles the app's own glance view (not yet verified on
      this host, so review what it draws).

    The two non-glance profiles require the generated jungle, because an
    explicit one cannot be rebased onto the stubbed source.

    ``settings`` compiles the app's property defaults in: a modified
    ``settings.xml`` is written next to the generated jungle and appended to the
    device's ``resourcePath`` right after ``$(resBase)``. The defaults the
    compiler emitted are read back and asserted, so a run cannot silently end up
    with an empty server URL.
    """
    if not layout.monkeyc.is_file():
        raise BuildError(f"monkeyc not found at {layout.monkeyc}")
    if profile not in PROFILES:
        raise BuildError(f"unknown build profile {profile!r}; expected {', '.join(PROFILES)}")

    include_glance = profile == PROFILE_WITH_GLANCE
    profile_note = describe_profile(profile)
    rebase: Optional[Mapping[Path, Path]] = None
    manifest: Optional[Path] = None

    if jungle is None:
        source = jungle_path()
        source_root = source.resolve().parent
        if not include_glance:
            overlay = write_glance_excluded_source(source_root, output_dir)
            rebase = {source_root / "source": overlay / "source"}
            profile_note += f"; stub in {overlay / GLANCE_VIEW}"
        if profile == PROFILE_WATCH_APP:
            manifest = write_watch_app_manifest(source_root, output_dir).resolve()
            profile_note += f"; manifest {manifest}"
        target = Path(output_dir) / f"{device}.jungle"
        try:
            generated = generate_device_jungle(
                source,
                device,
                target,
                settings=settings,
                settings_source=settings_source,
                manifest=manifest,
                environ=env,
                rebase=rebase,
            )
        except JungleError as error:
            raise BuildError(str(error)) from None
        jungle_file = generated.path
        jungle_generated = True
        kept = ", ".join(generated.sections)
        override_note = (
            f"; settings override {generated.resource_override}"
            if generated.resource_override is not None
            else ""
        )
        jungle_note = (
            f"generated {jungle_file} from {source} ({kept}) because the full "
            "jungle names every supported device and a reduced SDK cannot "
            f"validate them{override_note}; pass --jungle to use a full one "
            "with a complete SDK"
        )
    else:
        if settings is not None:
            raise BuildError(
                "--jungle cannot carry the harness settings override: only a "
                "generated jungle can add the resource directory that sets the "
                "app's compiled property defaults.\n"
                "Drop --jungle (the generated jungle works with any SDK that "
                "defines the device), or pass --prg with a PRG you built "
                "yourself."
            )
        if not include_glance:
            raise BuildError(
                f"--jungle cannot carry the {profile} profile: the profile "
                "rebases the generated jungle's sourcePath onto a stubbed copy "
                "of source/ (and may point project.manifest at a generated "
                "manifest), which an explicit jungle cannot express. Drop "
                "--jungle, or build with --with-glance; the glance is not yet "
                "verified on this host."
            )
        jungle_file = Path(jungle)
        if not jungle_file.is_file():
            raise BuildError(f"Monkey Jungle not found at {jungle_file}")
        jungle_generated = False
        jungle_note = (
            f"using the explicit jungle {jungle_file} (--jungle); the SDK must "
            "define every device it names"
        )

    output_dir.mkdir(parents=True, exist_ok=True)
    output = output_dir / prg_name(device)

    command = [
        str(layout.monkeyc),
        "-f",
        str(jungle_file),
        "-o",
        str(output),
        "-d",
        device,
        "-w",
    ]
    if developer_key is not None:
        command += ["-y", str(developer_key)]
    if release:
        command.append("-r")
    command += list(extra_args)

    started = time.monotonic()
    try:
        completed = subprocess.run(  # noqa: S603 - fixed argument list
            command,
            capture_output=True,
            text=True,
            timeout=600,
            env=env,
        )
    except FileNotFoundError as error:
        raise BuildError(f"cannot run {command[0]}: {error}") from None
    except subprocess.TimeoutExpired:
        raise BuildError(f"monkeyc timed out after 600s for device {device}") from None
    duration_ms = (time.monotonic() - started) * 1000.0

    output_text = (completed.stdout or "") + (completed.stderr or "")
    if completed.returncode != 0:
        rejected = invalid_qualifiers(output_text)
        if rejected:
            raise BuildError(qualifier_error(device, rejected, jungle_file))
        raise BuildError(
            f"monkeyc failed for device {device} (exit {completed.returncode}):\n"
            f"{output_text.strip()}"
        )
    if not output.is_file():
        raise BuildError(
            f"monkeyc reported success but {output} does not exist:\n{output_text.strip()}"
        )

    settings_json: Optional[Path] = None
    settings_values: Dict[str, Any] = {}
    if settings is not None:
        settings_json, settings_values = verify_compiled_settings(output, settings)

    return BuildResult(
        prg=output,
        command=tuple(command),
        output=output_text.strip(),
        duration_ms=duration_ms,
        jungle=jungle_file,
        jungle_generated=jungle_generated,
        jungle_note=jungle_note,
        settings_json=settings_json,
        settings_values=settings_values,
        profile=profile,
        profile_note=profile_note,
    )


def available(monkeyc: Path) -> bool:
    """True when the compiler file exists (executability is checked on run)."""
    return monkeyc.is_file()
