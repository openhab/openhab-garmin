"""PRG compilation with the Linux ``monkeyc``.

The runner image contains the compiler, never the app's build output: every
scenario run compiles the checkout it was mounted with, so a run always tests
the code under review.

Debug annotations matter here. The app's ``(:debug)`` trace events (the
``E2E:`` console lines used by protocol-tier assertions) are stripped from
release builds, so the harness builds without ``--release`` by default.

The app's real glance view is not exercised by default: the harness builds a
profile that stubs it, so a run always launches the app's normal initial view.
The draw crash that once forced this (``Invalid Font Specified`` in
``GlanceSitemapView.onUpdate``) was the empty device font pack, which the runner
now stages, and the app opens from the glance with DOWN then SELECT. Whether the
real glance renders under ``--with-glance`` has not been measured since the pack
landed, so it is **unverified**, not a known failure. The harness therefore has
two named build profiles:

``without-glance`` (the default for scenarios)
    The glance view is replaced by an empty stub in a generated copy of
    ``source/``. The rest of the app, including ``OHApp.getGlanceView()``, is
    unchanged, so the app launches into its normal initial view and can poll
    openHAB.

``with-glance``
    The app's own glance view is compiled (``--with-glance``). Use it on
    hardware, or to capture and verify the glance for the first time.

``monkeyc -x glance`` is not usable: ``-x`` is rejected together with ``-f``
(``The -f command line option is incompatible with the options -x, -m, -z``),
and the jungle's ``excludeAnnotations = glance`` cannot stand in either,
because the manifest entry class ``OHApp`` and shared classes such as
``SitemapStore``, ``E2ETrace`` and ``AppLifecycle`` carry ``(:glance)`` too.
Excluding the annotation removes the entry point and the app does not build.
The stub is therefore the nearest equivalent that keeps the app compilable;
the annotation itself is left untouched.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time
from contextlib import contextmanager
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterator, Mapping, Optional, Sequence, Tuple

from .config import jungle_path
